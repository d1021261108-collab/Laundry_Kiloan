import streamlit as st

st.set_page_config(page_title="Laundry Kiloan")
st.title("Perhitungan Biaya Laundry Kiloan")


def rupiah(angka):
    return "Rp " + f"{angka:,}".replace(",", ".")


# Nilai awal session state
if "nim" not in st.session_state:
    st.session_state.nim = ""
if "berat" not in st.session_state:
    st.session_state.berat = 0
if "hasil" not in st.session_state:
    st.session_state.hasil = None
if "error" not in st.session_state:
    st.session_state.error = None


def hitung():
    nim = st.session_state.nim.strip()
    berat = st.session_state.berat
    st.session_state.hasil = None
    st.session_state.error = None

    # Validasi NIM: harus 10 digit angka
    if not (nim.isdigit() and len(nim) == 10):
        st.session_state.error = "NIM tidak valid! NIM harus terdiri dari tepat 10 digit angka."
        return

    # Validasi berat: harus lebih dari 0
    if berat <= 0:
        st.session_state.error = "Berat cucian tidak valid! Berat harus lebih dari 0."
        return

    # Perhitungan
    tarif = 5000 + int(nim[-1]) * 500
    digit_genap = sum(1 for d in nim if int(d) % 2 == 0)
    diskon = digit_genap  # persen
    biaya_normal = berat * tarif
    potongan = diskon * biaya_normal // 100
    total = biaya_normal - potongan

    st.session_state.hasil = {
        "tarif": tarif,
        "genap": digit_genap,
        "diskon": diskon,
        "normal": biaya_normal,
        "potongan": potongan,
        "total": total,
    }


def reset():
    st.session_state.nim = ""
    st.session_state.berat = 0
    st.session_state.hasil = None
    st.session_state.error = None


# Input
st.text_input("NIM (10 digit)", key="nim")
st.number_input("Berat Cucian (kg)", min_value=0, step=1, key="berat")

# Tombol
col1, col2 = st.columns(2)
col1.button("Hitung", on_click=hitung)
col2.button("Reset", on_click=reset)

# Output
if st.session_state.error:
    st.error(st.session_state.error)

h = st.session_state.hasil
if h:
    st.subheader("Hasil Perhitungan")
    st.write(f"Tarif per kg : {rupiah(h['tarif'])}")
    st.write(f"Jumlah digit genap : {h['genap']}")
    st.write(f"Persen diskon : {h['diskon']} %")
    st.write(f"Biaya normal : {rupiah(h['normal'])}")
    st.write(f"Potongan : {rupiah(h['potongan'])}")
    st.success(f"Total bayar : {rupiah(h['total'])}")